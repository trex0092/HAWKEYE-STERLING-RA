/* SECONDARY ALERT CHANNEL: GitHub Issue for FAILED daily delivery.

   Default OFF. This is a separate destination from Asana, but the same
   GitHub Actions infrastructure, not a geographically independent monitor.
   Do not enable until MLRO/IT approve public-repo operational alert exposure
   and run owner sign-off. Never include customer or transaction data.
   All source inputs are generated by the trusted workflow, NOT model text.
   No runtime npm dependencies.
*/
import { pathToFileURL } from 'node:url';

export const TITLE = '[HAWKEYE ALERT] Daily screening report delivery not verified';

function validRepo(repo) {
  return typeof repo === 'string' &&
    /^[A-Za-z0-9_.-]{1,100}\/[A-Za-z0-9_.-]{1,100}$/.test(repo);
}

export function sanitizedAlert(env, now) {
  const repo = String(env.GITHUB_REPOSITORY || '');
  const runId = String(env.GITHUB_RUN_ID || '');
  if (!validRepo(repo) || !/^\d{1,20}$/.test(runId)) {
    throw Error('GitHub alert context is missing or malformed');
  }
  if (!(now instanceof Date) || !Number.isFinite(now.getTime())) {
    throw Error('GitHub alert timestamp missing');
  }
  return {
    title: TITLE,
    body: [
      'Daily screening report delivery could not be verified by the delivery watchdog.',
      '',
      '**State:** DELIVERY UNVERIFIED. Treat as an operational incident; do not interpret as an all-clear.',
      '**Detected (UTC):** ' + now.toISOString(),
      '**Workflow run:** https://github.com/' + repo + '/actions/runs/' + runId,
      '',
      'Escalate to the MLRO/IT owner. Check the underlying workflow and the approved',
      'screening delivery evidence. Verify the report and its full-results attachments',
      'from an authorized location. Do not post customer names, payment identifiers,',
      'screening results, confidential cases or tokens in this public issue.',
      '',
      'This issue is intentionally generic and is NOT evidence of incident closure.'
    ].join('\n')
  };
}

export function findOpenDuplicate(items) {
  if (!Array.isArray(items)) throw Error('GitHub alert lookup returned invalid data');
  return items.find(item => item && !item.pull_request && item.state === 'open' &&
    item.title === TITLE) || null;
}

export async function deliverSecondaryAlert({
  env = process.env, fetchImpl = fetch, now = new Date()
} = {}) {
  if (String(env.SECONDARY_ALERT_ENABLED || '') !== 'true') {
    return { state: 'DISABLED' };
  }
  const alert = sanitizedAlert(env, now);
  const token = String(env.GITHUB_TOKEN || '');
  if (token.length < 10 || token.length > 4096) {
    throw Error('GitHub secondary alert token not configured');
  }
  const repo = env.GITHUB_REPOSITORY;
  const base = 'https://api.github.com/repos/' + repo;
  const headers = {
    Authorization: 'Bearer ' + token,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
    'User-Agent': 'hawkeye-screening-delivery-secondary-alert'
  };
  const call = async (method, url, data) => {
    const response = await fetchImpl(url, {
      method,
      headers: { ...headers, ...(data ? { 'Content-Type': 'application/json' } : {}) },
      body: data ? JSON.stringify(data) : undefined,
      redirect: 'error', signal: globalThis.AbortSignal.timeout(15000)
    });
    if (!response.ok) {
      throw Error('GitHub secondary alert API returned HTTP ' + response.status);
    }
    const json = await response.json();
    if (!json || typeof json !== 'object') throw Error('Invalid GitHub alert API response');
    return json;
  };
  // Refuse to create a possible duplicate if the open-issue scan is incomplete
  // or fails. This is idempotency best-effort, not an atomic transaction.
  for (let page = 1; page <= 20; page++) {
    const issues = await call('GET',
      base + '/issues?state=open&per_page=100&page=' + page);
    if (!Array.isArray(issues)) throw Error('GitHub open-issue list missing');
    const match = findOpenDuplicate(issues);
    if (match) return { state: 'ALREADY_OPEN', number: match.number || null };
    if (issues.length < 100) {
      const made = await call('POST', base + '/issues', alert);
      if (!Number.isSafeInteger(made.number) || !/^https:\/\/github\.com\//.test(made.html_url || '')) {
        throw Error('GitHub did not confirm the new issue');
      }
      return { state: 'CREATED', number: made.number };
    }
  }
  throw Error('Open-issue scan capped; cannot prove absence of duplicate');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const result = await deliverSecondaryAlert();
    console.log('secondary-alert: ' + result.state +
      (result.number ? ' issue #' + result.number : ''));
  } catch (e) {
    console.error('secondary-alert: NOT DELIVERED (' + String(e && e.message || e).slice(0, 170) + ')');
    process.exitCode = 1;
  }
}
